import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

PREFIX = os.environ.get("RISCV_PREFIX", "riscv64-unknown-elf-")

TEMPLATE = """\
// Copyright 2026 FER, HPC Architecture and Application Research Center
// SPDX-License-Identifier: Apache-2.0 WITH SHL-2.1
//
// Licensed under the Solderpad Hardware License v 2.1 (the "License");
// you may not use this file except in compliance with the License, or,
// at your option, the Apache License version 2.0.
// You may obtain a copy of the License at https://solderpad.org/licenses/SHL-2.1/

// AUTO-GENERATED by scripts/gen_zsbl_rom.py from {source}, do not edit.
//
// ZSBL boot ROM contents. Synchronous read, one cycle latency.
module friscv_zsbl_rom #(
    parameter int unsigned Words = 256
) (
    input  logic                     clk_i,
    input  logic [$clog2(Words)-1:0] addr_i,
    output logic [31:0]              rdata_o
);

localparam int unsigned ProgWords = {num_words};

if (ProgWords > Words) begin : gen_too_small
    $error("ZSBL program ({num_words} words) does not fit in the ROM");
end

(* rom_style = "block" *) logic [31:0] mem [Words];

initial begin
    for (int unsigned i = 0; i < Words; i++) mem[i] = 32'h0000_0000;

    // Program at 0x{start_addr:08x}
{instructions}
end

always_ff @(posedge clk_i) begin
    rdata_o <= mem[addr_i];
end

endmodule
"""


def run(cmd: list[str]) -> str:
    try:
        return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    except FileNotFoundError:
        sys.exit(f"ERROR: {cmd[0]} not found (set RISCV_PREFIX to change the toolchain prefix)")
    except subprocess.CalledProcessError as e:
        sys.exit(f"ERROR: {' '.join(cmd)} failed:\n{e.stderr}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="ZSBL assembly source")
    parser.add_argument("output", type=Path, help="generated SystemVerilog ROM")
    parser.add_argument("--linker-script", type=Path, required=True)
    parser.add_argument("--sim", action="store_true", help="assemble with SIMULATION=1")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        obj = Path(tmp) / "zsbl.o"
        elf = Path(tmp) / "zsbl.elf"
        binf = Path(tmp) / "zsbl.bin"

        as_cmd = [f"{PREFIX}as", "-march=rv32i_zicsr", "-mabi=ilp32", "-o", str(obj)]
        if args.sim:
            as_cmd += ["--defsym", "SIMULATION=1"]
        run(as_cmd + [str(args.source)])
        run([f"{PREFIX}ld", "-m", "elf32lriscv", "-T", str(args.linker_script), "-o", str(elf), str(obj)])
        run([f"{PREFIX}objcopy", "-O", "binary", "--only-section=.text", str(elf), str(binf)])
        raw = binf.read_bytes()
        dump = run([f"{PREFIX}objdump", "-d", "-M", "no-aliases,numeric", str(elf)])
        symbols = {f[2]: int(f[0], 16) for f in map(str.split, run([f"{PREFIX}nm", str(elf)]).splitlines())
                   if len(f) == 3}
        start = symbols["_start"]

    mnemonics = {}
    for line in dump.splitlines():
        m = re.match(r"^\s*([0-9a-f]+):\s+[0-9a-f]+\s+(.+)", line)
        if m:
            mnemonics[int(m.group(1), 16)] = " ".join(m.group(2).split())

    raw += b"\x00" * (-len(raw) % 4)
    lines = []
    for i in range(len(raw) // 4):
        word = int.from_bytes(raw[i * 4:i * 4 + 4], "little")
        comment = mnemonics.get(start + i * 4, "")
        lines.append(f"    mem[{i}] = 32'h{word >> 16:04x}_{word & 0xffff:04x};  // {comment}".rstrip())

    args.output.write_text(TEMPLATE.format(
        source=args.source.name,
        num_words=len(lines),
        start_addr=start,
        instructions="\n".join(lines),
    ), newline="\n")
    print(f"{args.output}: {len(raw)} bytes ({len(lines)} words)")


if __name__ == "__main__":
    main()
